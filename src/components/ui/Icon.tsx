export type BrandName = keyof typeof BRAND_PATHS;
export type LineName = keyof typeof LINE_PATHS;
export type IconName = BrandName | LineName;

const isBrand = (n: IconName): n is BrandName => n in BRAND_PATHS;

export function Icon({
  name,
  className = 'h-5 w-5',
  title,
}: {
  name: IconName;
  className?: string;
  /** Give a title only when the icon is the sole label. Otherwise leave it out
      and let the parent control carry the accessible name — a title here plus a
      label there means a screen reader announces the thing twice. */
  title?: string;
}) {
  const labelled = title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true as const };

  if (isBrand(name)) {
    // Official marks are filled, not stroked. Do not restyle the geometry.
    return (
      <svg viewBox="0 0 24 24" fill="currentColor" className={className} {...labelled}>
        <path d={BRAND_PATHS[name]} />
      </svg>
    );
  }

  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.7}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      {...labelled}
    >
      {LINE_PATHS[name]}
    </svg>
  );
}

